def load_text() -> str:
    reader = PdfReader(str(PDF))
    text = ""
    for page in reader.pages:
        text += page.extract_text() + "\n"
    # NFKC folds CJK-compat glyphs the PDF uses (⼈→人, 前年⽐→前年比,
    # fullwidth digits → ASCII) so the regexes below can match.
    text = unicodedata.normalize("NFKC", text)
    # Strip kerning spaces between CJK chars
    text = re.sub(r"(?<=[぀-ヿ㐀-鿿])\s+(?=[぀-ヿ㐀-鿿])", "", text)
    text = re.sub(r"[ \t]+", " ", text)
    return text


def parse_market_timeseries(text: str, jp_name: str) -> list[dict]:
    """Parse the per-market 年別推移 block: lines like
    '2000年：4,757,146人、前年比 +4.7%' (first year has no YoY)."""
    # Isolate the block starting at 【<name>】 up to the next 【...】 or 出典
    m = re.search(rf"【{re.escape(jp_name)}】(.+?)(?=【|出典|四、|$)", text, re.DOTALL)
    if not m:
        return []
    block = m.group(1)
    rows = []
    for line in re.finditer(
        r"(\d{4})年:([\d,]+)人(?:、前年比\s*([+\-][\d.]+%|[^\d、]*))?",
        block,
    ):
        year = int(line.group(1))
        value = line.group(2)
        yoy = (line.group(3) or "").strip()
        row = {"年": year, "人数": f"{value}人"}
        if yoy:
            row["前年比"] = yoy
        rows.append(row)
    return rows


def parse_annual_total(text: str) -> list[dict]:
    m = re.search(r"二、訪日外客数の年別推移(.+?)(?=三、)", text, re.DOTALL)
    if not m:
        return []
    rows = []
    for line in re.finditer(
        r"(\d{4})年(?:\(暫定\))?:(約?[\d,]+)人?、前年比\s*(約?[+\-][\d.]+%|コロナ[^0-9\n]*?参考値)",
        m.group(1),
    ):
        rows.append(
            {
                "年": int(line.group(1)),
                "人数": line.group(2).replace("約", "約 "),
                "前年比": line.group(3).strip(),
            }
        )
    return rows


